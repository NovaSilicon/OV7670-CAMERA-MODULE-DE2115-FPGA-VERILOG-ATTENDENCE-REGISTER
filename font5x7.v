// Shared combinational 5x7 font ROM. Each glyph is 7 rows of 5 bits, packed
// row 0 first; bit (34 - row*5 - column) is the pixel at (column,row), with
// column 0 the leftmost. Unlisted characters (including space) are blank.
// Glyphs A..W and digits are unchanged from the original identity overlay.
// R and S were added for the attendance strings PRESENT and NOT MARKED.
// B C F G L X Y, digits 1 3 7 8 9 and '/' ':' were added for the box label,
// enrolment prompts and the hex score read-out.
